"""Tables from results_cluster/*.jsonl (aggregates exported by export_safe.py) -> RESULTS.md.
Runs locally; reads nothing patient-level."""
import json
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parents[1]
RC = HERE / "results_cluster"


def load(name):
    f = RC / f"{name}.jsonl"
    if not f.exists():
        return pd.DataFrame()
    rows = [json.loads(l) for l in f.read_text().splitlines() if l.strip()]
    df = pd.DataFrame(rows)
    # keep the last write of every configuration
    return df


def pct(x, d=1):
    try:
        return f"{100 * float(x):.{d}f}"
    except (TypeError, ValueError):
        return str(x)


def md(df):
    return df.to_markdown(index=False) if len(df) else "_(none yet)_"


def dedupe(df, keys):
    if not len(df):
        return df
    return df.drop_duplicates(subset=[k for k in keys if k in df], keep="last")


def main():
    out = ["# Results (aggregates)", "",
           "Generated by `scripts/report.py` from `results_cluster/` (counts 1-9 masked). "
           "Shares in %. K = 5 unless stated.", ""]
    fl = dedupe(load("floor_levels"), ["db", "hierarchy", "K", "m", "L"])
    out += ["## 1. The refusal floor against the top of the hierarchy", ""]
    for db in ("mimic", "eicu"):
        d = fl[fl.db == db] if len(fl) else fl
        if not len(d):
            continue
        for hn in ("official", "trunc"):
            t = d[d.hierarchy == hn]
            if not len(t):
                continue
            piv = t.pivot_table(index=["K", "m"], columns="level", values="refused_share",
                                aggfunc="last")
            order = [c for c in ["raw", "category", "3 chars", "block", "2 chars / 1 char",
                                 "chapter", "root"] if c in piv.columns]
            piv = (piv[order] * 100).round(2).reset_index()
            out += [f"**{db}, {hn} tree: refused share by top level**", "", md(piv), ""]
        t = d[(d.hierarchy == "official") & (d.K == 5)]
        cols = [c for c in ["m", "level", "refused_share", "refused_share_gt14",
                            "death_removed_share", "death_rho", "readmit30_removed_share",
                            "readmit30_rho"] if c in t]
        tt = t[cols].copy()
        for c in cols[2:]:
            tt[c] = tt[c].map(lambda v: pct(v) if "rho" not in c else
                              (f"{v:.2f}" if isinstance(v, float) else v))
        out += [f"**{db}: who is refused (official tree, K = 5)**", "", md(tt), ""]
    fr = load("floor_fractions")
    if len(fr):
        out += ["## 2. Floor against population size", ""]
        g = (fr.groupby(["db", "hierarchy", "m", "level", "frac"]).refused_share
             .agg(["mean", "min", "max"]).reset_index())
        for db in g.db.unique():
            t = g[(g.db == db) & (g.m == 3)]
            piv = t.pivot_table(index=["hierarchy", "level"], columns="frac", values="mean")
            out += [f"**{db}, m = 3: mean refused share over seeds by population fraction**", "",
                    md((piv * 100).round(1).reset_index()), ""]
    st = load("floor_strata")
    if len(st):
        out += ["## 3. Floor against the strata", ""]
        piv = st[st.m == 3].pivot_table(index=["db", "hierarchy", "level"], columns="strata",
                                       values="refused_share", aggfunc="last")
        out += [md((piv * 100).round(1).reset_index()), ""]
    ho = load("floor_hospital")
    if len(ho):
        out += ["## 4. Each hospital releasing alone vs the network (eICU)", ""]
        cols = ["hierarchy", "m", "level", "strata", "refused_share"] + \
            [c for c in ho.columns if c.startswith("refused_share_hosp_")]
        t = dedupe(ho, ["hierarchy", "m", "L", "strata"])[cols].copy()
        for c in cols[4:]:
            t[c] = t[c].map(pct)
        t.columns = [c.replace("refused_share_hosp_", "hosp ") for c in t.columns]
        out += [md(t), ""]
    rel = load("releases")
    if len(rel):
        rel["strata"] = rel["strata"].fillna("band") if "strata" in rel else "band"
    rel = dedupe(rel, ["db", "hierarchy", "L", "m", "K", "frac", "strata", "method"])
    if len(rel):
        out += ["## 5. Releases under both counts", "",
                "removed = (patient, code) pairs not shown (refused or suppressed); raw = share "
                "of released entries at level 0; loss = mean NCP-style loss per entry (1 = "
                "suppressed/root); strict/loose viol = records with some itemset/code set "
                "seen by < K records; unique = some |E| = 1; len<K = record length held by "
                "< K records of the stratum; attack = mean success of the most-specific-match "
                "attack (certain = success 1).", ""]
        for (db, h, L, m, K, frac, st), t in rel.groupby(["db", "hierarchy", "L", "m", "K", "frac",
                                                          "strata"]):
            cols = ["method", "refused_share", "entries_removed_share", "share_level0",
                    "mean_loss", "empty_share", "strict_violator_share", "strict_unique_share",
                    "loose_violator_share", "length_lt_K_share", "attack_mean",
                    "attack_certain", "build_s"]
            tt = t[[c for c in cols if c in t]].copy()
            for c in tt.columns[1:-1]:
                tt[c] = tt[c].map(lambda v: pct(v, 2) if c != "mean_loss" else f"{v:.3f}")
            tt["build_s"] = tt["build_s"].map(lambda v: f"{v:.0f}")
            tt.columns = ["method", "refused", "removed", "raw", "loss", "empty", "strict viol",
                          "unique", "loose viol", "len<K", "attack", "certain", "build s"][:len(tt.columns)]
            out += [f"**{db}, {h}, m = {m}, K = {K}" + (f", {frac:.0%} sample" if frac < 1 else "")
                    + (", every hospital releasing alone" if st == "hospital" else "")
                    + "**", "", md(tt), ""]
    ua = load("utility_arms")
    if len(ua):
        out += ["## 6. Utility: AUROC and difference to raw codes for everyone", ""]
        ua = dedupe(ua, ["db", "outcome", "arm"])
        for (db, oc), t in ua.groupby(["db", "outcome"]):
            tt = t[["arm", "auroc", "d_raw", "d_raw_lo", "d_raw_hi", "train_rows", "vocab"]].copy()
            tt["auroc"] = tt.auroc.map(lambda v: f"{v:.4f}")
            oc1 = t["one_class_splits"].fillna(0) if "one_class_splits" in t else [0] * len(t)
            tt["d_raw [NB 95%]"] = ["n/a (no events among released training rows)" if o > 0 else
                                   f"{a:+.4f} [{b:+.4f}, {c:+.4f}]"
                                   for a, b, c, o in zip(t.d_raw, t.d_raw_lo, t.d_raw_hi, oc1)]
            tt = tt[["arm", "auroc", "d_raw [NB 95%]", "train_rows", "vocab"]]
            out += [f"**{db}, outcome {oc}** (rows {int(t.rows.iloc[0])}, base rate "
                    f"{t.base_rate.iloc[0]:.3f})", "", md(tt), ""]
        up = load("utility_pairs")
        if len(up):
            up = dedupe(up, ["db", "outcome", "a", "b"])
            # only contrasts between releases of the same tree, level and m
            up = up[up.a.str.rsplit("_", n=1).str[0].str.replace(r"_(b3g?s?|floor|sloc\w*|apriori\w*|A|b2)$", "", regex=True)
                    == up.b.str.rsplit("_", n=1).str[0].str.replace(r"_(b3g?s?|floor|sloc\w*|apriori\w*|A|b2)$", "", regex=True)]
            for (db, oc), t in up.groupby(["db", "outcome"]):
                tt = pd.DataFrame({"a - b": [f"{x} - {y}" for x, y in zip(t.a, t.b)],
                                   "d [NB 95%]": [f"{a:+.4f} [{b:+.4f}, {c:+.4f}]"
                                                  for a, b, c in zip(t.d, t.lo, t.hi)]})
                out += [f"**{db}, {oc}: paired contrasts between releases**", "", md(tt), ""]
    # ---------------------------------------------------------------- further measurements ----
    def fmt_d(t):
        return [f"{a:+.4f} [{b:+.4f}, {c:+.4f}]" for a, b, c in zip(t.d_raw, t.d_raw_lo, t.d_raw_hi)]

    rf = load("utility_arms_rf")
    if len(rf) and len(ua):
        out += ["## 7. Robustness of the utility ranking to the model family", "",
                "Same protocol, random forest (200 trees, min leaf 5) instead of logistic "
                "regression. d_raw = AUROC difference to raw codes on everyone.", ""]
        rf = dedupe(rf, ["db", "outcome", "arm"])
        lr = ua[["db", "outcome", "arm", "d_raw", "d_raw_lo", "d_raw_hi", "auroc"]]
        for (db, oc), t in rf.groupby(["db", "outcome"]):
            t = t.merge(lr, on=["db", "outcome", "arm"], suffixes=("_rf", "_lr"), how="left")
            t = t[~t.arm.str.contains(":randmatch|_len_|_w0|_w2|_w4|m4")]
            tt = pd.DataFrame({"arm": t.arm,
                               "AUROC LR": t.auroc_lr.map(lambda v: f"{v:.4f}" if v == v else ""),
                               "d_raw LR": [f"{a:+.4f}" if a == a else "" for a in t.d_raw_lr],
                               "AUROC RF": t.auroc_rf.map(lambda v: f"{v:.4f}"),
                               "d_raw RF [NB 95%]": [f"{a:+.4f} [{b:+.4f}, {c:+.4f}]" for a, b, c in
                                                     zip(t.d_raw_rf, t.d_raw_lo_rf, t.d_raw_hi_rf)]})
            out += [f"**{db}, outcome {oc}: LR vs RF**", "", md(tt), ""]
    pm = load("utility_pairs_match")
    if len(pm):
        out += ["## 8. Matched random controls", "",
                "`X:randmatch` removes, in every split, as many random training patients as "
                "release X refuses, and codes the rest exactly as X. d = AUROC(X) - "
                "AUROC(control): negative means the floor's choice of whom to refuse costs "
                "more than removing the same number at random.", ""]
        pm = dedupe(pm, ["db", "outcome", "a", "b"])
        pm = pm[pm.b.str.endswith(":randmatch") & (pm.a + ":randmatch" == pm.b)]
        am = dedupe(load("utility_arms_match"), ["db", "outcome", "arm"])
        for (db, oc), t in pm.groupby(["db", "outcome"]):
            t = t.merge(am[["db", "outcome", "arm", "d_raw"]].rename(columns={"arm": "a", "d_raw": "d_rel"}),
                        on=["db", "outcome", "a"], how="left")
            t = t.merge(am[["db", "outcome", "arm", "d_raw"]].rename(columns={"arm": "b", "d_raw": "d_ctl"}),
                        on=["db", "outcome", "b"], how="left")
            tt = pd.DataFrame({"release": t.a,
                               "d_raw release": [f"{v:+.4f}" if v == v else "" for v in t.d_rel],
                               "d_raw control": [f"{v:+.4f}" if v == v else "" for v in t.d_ctl],
                               "release - control [NB 95%]": [f"{a:+.4f} [{b:+.4f}, {c:+.4f}]"
                                                               for a, b, c in zip(t.d, t.lo, t.hi)]})
            out += [f"**{db}, {oc}**", "", md(tt), ""]
    ra = load("reaudit")
    if len(ra):
        ra = dedupe(ra, ["key"])
        ra = ra[ra.K == 5]
        main_m = ["floor", "b3g", "slocL", "sloc0", "b3s", "b3gs"]
        out += ["## 9. Length-augmented audit", "",
                "Strict audit with the released record length as an always-known extra item "
                "(an adversary who knows m codes AND how many codes the record shows). All these "
                "releases have 0 strict violators; the shares below are entirely the length leak. "
                "strata = band (sex x age) or len (sex x age x length band); hosp = each hospital "
                "alone.", ""]
        t = ra[ra.method.isin(main_m)]
        piv = t.pivot_table(index=["db", "L", "m", "strata"], columns="method",
                            values="lenaud_violator_share", aggfunc="last")
        piv = piv[[c for c in main_m if c in piv.columns]]
        if len(rel):
            r2 = rel[(rel.K == 5) & rel.method.isin(["floor", "slocL"])].copy()
            r2["strata"] = r2.strata.map({"band": "band", "hospital": "hosp", "length": "len"})
            r2 = r2.pivot_table(index=["db", "L", "m", "strata"], columns="method",
                                values="length_lt_K_share", aggfunc="last")
            r2.columns = [f"len<K alone ({c})" for c in r2.columns]
            piv = piv.join(r2, how="left")
        out += ["**violator share under the length-augmented audit (%)**; the last columns give "
                "the share of released records whose released length alone is held by fewer than "
                "K records of the stratum", "",
                md((piv * 100).round(1).reset_index()), ""]
        piv = t.pivot_table(index=["db", "L", "m", "strata"], columns="method",
                            values="lenaud_unique_share", aggfunc="last")
        piv = piv[[c for c in main_m if c in piv.columns]]
        out += ["**unique share under the length-augmented audit (%)**", "",
                md((piv * 100).round(1).reset_index()), ""]
        out += ["## 10. Visible refusal and visible suppression", "",
                "Share of targets for whom an adversary with the stratum and m random true codes "
                "finds no loose candidate at all. Refused targets (floor-type releases) and "
                "released targets with at least one suppressed code (suppression releases); "
                "up to 20,000 targets each.", ""]
        t = ra[ra.method.isin(main_m) & (ra.strata != "hosp")].copy()
        t["visible"] = t.refused_no_candidate_share.fillna(t.suppressed_no_candidate_share)
        piv = t.pivot_table(index=["db", "L", "m", "strata"], columns="method", values="visible",
                            aggfunc="last")
        piv = piv[[c for c in main_m if c in piv.columns]]
        out += [md((piv * 100).round(1).reset_index()), ""]
        out += ["## 11. Count-query error at the release level", "",
                "Count queries at the level the release targets (q = L, block or chapter): "
                "mean absolute relative error over all nodes with support (single), the share of "
                "total support lost, and the same for the 100 most frequent node pairs. Strings "
                "released above the query level cannot answer it.", ""]
        rows = []
        for _, r in ra[ra.method.isin(main_m + ["b3s_w0.25", "b3gs_w0.25"]) & (ra.strata != "hosp")].iterrows():
            q = f"q{int(r.L)}_"
            if q + "single_mare" not in ra.columns or not (r[q + "single_mare"] == r[q + "single_mare"]):
                continue
            rows.append(dict(db=r.db, L=int(r.L), m=int(r.m), strata=r.strata, method=r.method,
                             **{"single MARE": pct(r[q + "single_mare"]),
                                "single support lost": pct(r[q + "single_support_lost"]),
                                "pair MARE": pct(r[q + "pair_mare"]),
                                "pair support lost": pct(r[q + "pair_support_lost"]),
                                "single MARE rescaled": pct(r[q + "single_mare_rescaled"])}))
        out += [md(pd.DataFrame(rows).sort_values(["db", "L", "m", "strata", "method"])), ""]
        out += ["## 12. Whom the release hurts", "",
                "Share of (patient, code) entries removed, by the patient's record length band and "
                "sex; share of patients refused by length band; rho = share of outcome events among "
                "refused patients / share of patients refused (>1: refusal concentrates on events).", ""]
        lens = ["1-2", "3-5", "6-10", "11-20", ">=21"]
        rows = []
        for _, r in ra[ra.method.isin(main_m) & (ra.strata == "band") & (ra.m == 3)].iterrows():
            d = dict(db=r.db, L=int(r.L), method=r.method)
            for lb in lens:
                d[f"rem {lb}"] = pct(r.get(f"removed_len_{lb}"))
            for lb in lens:
                d[f"ref {lb}"] = pct(r.get(f"refused_len_{lb}"))
            sf = next((r[c] for c in ("removed_sex_Female", "removed_sex_F") if c in r and r[c] == r[c]), None)
            sm = next((r[c] for c in ("removed_sex_Male", "removed_sex_M") if c in r and r[c] == r[c]), None)
            d["rem F"] = pct(sf)
            d["rem M"] = pct(sm)
            for oc in ("death", "readmit30"):
                v = r.get(f"{oc}_rho_refusal")
                if v == v and v is not None:
                    d[f"rho {oc}"] = f"{v:.2f}"
                v = r.get(f"{oc}_rho_entries")
                if v == v and v is not None:
                    d[f"rho entries {oc}"] = f"{v:.2f}"
            rows.append(d)
        out += [md(pd.DataFrame(rows).sort_values(["db", "L", "method"]).fillna("")), ""]
    (HERE / "RESULTS.md").write_text("\n".join(out))
    print(f"wrote {HERE / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
